#!/usr/bin/env node
// Builds the syllabus coverage matrix (data/coverage/matrix.json and docs/COVERAGE_MATRIX.md) from verified inputs only.
// It reports coverage honestly and never claims 100%.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkLOs } from './check-los.js';
import { loadRegistry } from '../engine/registry.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const registry = loadRegistry(`${root}/sources/registry.json`);
const lo = JSON.parse(readFileSync(`${root}/data/syllabus_los.json`, 'utf8'));
const cur = JSON.parse(readFileSync(`${root}/data/curriculum.json`, 'utf8'));
const bank = JSON.parse(readFileSync(`${root}/data/questions.json`, 'utf8'));
const checks = new Map(checkLOs(root).results.map((r) => [r.id, r.status]));

// UNVERIFIED hints from model memory about which standards usually relate to each area. Never used as evidence by the
// tutor (they are not in the corpus) and must be confirmed against the ACCA examinable documents, which are not supplied.
const HINTS = {
  A1: ['IFRS Accounting Standards ethics context; professional code of ethics'],
  B1: ['Conceptual Framework for Financial Reporting'],
  C1: ['IFRS 15'], C2: ['IAS 16', 'IAS 36', 'IFRS 5', 'IAS 40', 'IAS 38', 'IAS 23'], C3: ['IFRS 9', 'IAS 32', 'IFRS 7'], C4: ['IFRS 16'], C5: ['IAS 19'], C6: ['IAS 12'],
  C7: ['IAS 37', 'IAS 10'], C8: ['IFRS 2'], C9: ['IFRS 13'], C10: ['IAS 1 and/or its replacement (applicability for the session unresolved)', 'IAS 7', 'IAS 8'], C11: ['IAS 20', 'IAS 8', 'IAS 24', 'IFRS for SMEs'],
  D1: ['IFRS 3', 'IFRS 10', 'IFRS 5', 'IAS 27', 'IAS 7'], D2: ['IAS 28', 'IFRS 11'], D3: ['IAS 21'], E1: ['IAS 33', 'IFRS 8', 'management commentary guidance'], F1: ['IFRS S1', 'IFRS S2', 'ESRS'], G: [],
};
const secOf = (id) => (id[0] === 'G' ? 'G' : id[0] + id.slice(1).replace(/[a-z]+$/, ''));
const lessonsFor = new Map(); const qFor = new Map();
for (const m of cur.modules) for (const l of m.lessons) for (const r of l.syllabusRefs ?? []) { (lessonsFor.get(r) ?? lessonsFor.set(r, []).get(r)).push({ id: l.id, status: l.status }); }
for (const q of bank.questions) for (const r of q.syllabusRefs) (qFor.get(r) ?? qFor.set(r, []).get(r)).push(q.id);

const rows = lo.los.map((x) => {
  const lessons = lessonsFor.get(x.id) ?? [];
  const qs = qFor.get(x.id) ?? [];
  const hasVerifiedLesson = lessons.some((l) => l.status === 'verified-from-sources');
  const gaps = [];
  if (!hasVerifiedLesson) gaps.push('No verified technical lesson: authoritative standard text and ACCA examinable documents not supplied.');
  if (!qFor.get(x.id)) gaps.push('No verified scored question.');
  gaps.push('No official ACCA question or marking scheme available.');
  return {
    id: x.id, area: x.area, section: x.section, outcome: x.label, level: x.level, syllabusPage: x.page,
    syllabusCheck: checks.get(x.id),
    relatedStandardsUnverifiedHint: HINTS[secOf(x.id)] ?? [], hintBasis: 'model memory; NOT verified; not examinability evidence',
    lessons, questions: qs, techniqueNote: x.level === 3 ? 'Level 3: synthesis and evaluation; expect scenario judgement and written explanation.' : x.level ? `Level ${x.level}.` : 'Employability and technology skills.',
    authoritativeSources: [{ sourceId: 'ACCA-SYL-SBRINT-2627', tier: 2, role: 'scope and level only', version: 'S26-J27', page: x.page }],
    session: registry.targetSession.id, examinability: 'in scope per syllabus; standard-level examinability unconfirmed (examinable documents not supplied)',
    contentStatus: hasVerifiedLesson ? 'partial' : 'scope-verified-content-pending', gaps,
  };
});
const total = rows.length;
const summary = {
  generated: 'by scripts/build-matrix.js', session: registry.targetSession.id, totalLearningOutcomes: total,
  syllabusScopeVerified: rows.filter((r) => r.syllabusCheck?.startsWith('verified')).length,
  withVerifiedTechnicalLesson: rows.filter((r) => r.lessons.some((l) => l.status === 'verified-from-sources')).length,
  withVerifiedScoredQuestion: rows.filter((r) => r.questions.length).length,
  coverageClaim: 'NOT CLAIMED. Technical teaching and assessment content cannot be verified until tier 1 sources and the examinable documents are supplied.',
  missingSources: registry.missingSources,
};
mkdirSync(`${root}/data/coverage`, { recursive: true });
writeFileSync(`${root}/data/coverage/matrix.json`, JSON.stringify({ summary, rows }, null, 1));

const md = [`# Syllabus coverage matrix (SBR-INT, ${registry.targetSession.id})`, '', '> Generated by `npm run matrix`. **Coverage is not claimed.**', '',
  `- Learning outcomes: **${total}** (page and intellectual level machine-checked against the ingested syllabus: **${summary.syllabusScopeVerified}/${total}**)`,
  `- With a verified technical lesson: **${summary.withVerifiedTechnicalLesson}/${total}**`,
  `- With at least one verified scored question: **${summary.withVerifiedScoredQuestion}/${total}**`, '',
  'The "related standards" column is an UNVERIFIED hint from model memory. It is not used as evidence by the tutor.', '',
  '| LO | Level | Outcome (own words) | p. | Syllabus check | Standards hint (unverified) | Lessons | Questions | Status |', '|---|---|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.id} | ${r.level ?? '-'} | ${r.outcome} | ${r.syllabusPage} | ${r.syllabusCheck} | ${r.relatedStandardsUnverifiedHint.join(', ') || '-'} | ${r.lessons.map((l) => `${l.id} (${l.status})`).join(', ') || '-'} | ${r.questions.join(', ') || '-'} | ${r.contentStatus} |`),
  '', '## Missing sources', '', ...registry.missingSources.map((m) => `- **${m.id}** (${m.status}): ${m.description}. Impact: ${m.impact}`)].join('\n');
mkdirSync(`${root}/docs`, { recursive: true });
writeFileSync(`${root}/docs/COVERAGE_MATRIX.md`, md + '\n');
console.log(JSON.stringify({ ...summary, missingSources: undefined }));
